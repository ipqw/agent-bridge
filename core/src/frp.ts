// frp configs. Secrets never land in a file: frp renders {{ .Envs.X }} templates at start,
// and the bridge passes the values to frpc through its environment.

import { appsEnabled, type Config } from "./config.js";
import type { Secrets } from "./secrets.js";

// Fixed visitor slot per service (place port = base + slot), so switching one gate off
// never moves the others and the place stays in step with the bridge.
export const SERVICE_SLOTS = { terminal: 0, browser: 1, apps: 2 } as const;
export type ServiceName = keyof typeof SERVICE_SLOTS;

export interface Exposed {
  name: ServiceName; // proxy name (frps prefixes it with the frp user = clientId)
  port: number; // local gate port
}

export function exposedServices(cfg: Config): Exposed[] {
  const out: Exposed[] = [];
  if (cfg.terminal.enabled) out.push({ name: "terminal", port: cfg.terminal.port });
  if (cfg.browser.enabled) out.push({ name: "browser", port: cfg.browser.port });
  if (appsEnabled(cfg)) out.push({ name: "apps", port: cfg.apps.port });
  return out;
}

// Client side (user's machine): stcp proxies for each gate. No inbound ports are opened.
export function frpcClientToml(cfg: Config): string {
  const lines = [
    "# generated by Agent Bridge — do not edit; secrets come from the environment",
    'serverAddr = "{{ .Envs.SB_FRPS_ADDR }}"',
    "serverPort = {{ .Envs.SB_FRPS_PORT }}",
    `user = "${cfg.frps.user || cfg.clientId}"`,
    'auth.method = "token"',
    'auth.token = "{{ .Envs.SB_FRPS_TOKEN }}"',
    "loginFailExit = false",
    'log.to = "console"',
    'log.level = "info"',
    "log.disablePrintColor = true",
    "",
  ];
  for (const s of exposedServices(cfg)) {
    lines.push(
      "[[proxies]]",
      `name = "${s.name}"`,
      'type = "stcp"',
      'secretKey = "{{ .Envs.SB_SK }}"',
      'localIP = "127.0.0.1"',
      `localPort = ${s.port}`,
      "",
    );
  }
  return lines.join("\n");
}

const changed = (a: unknown, b: unknown) => JSON.stringify(a) !== JSON.stringify(b);

// frpc must restart when its file changes or when frps moves (addr/port reach frpc via env, not the file).
export function needsFrpcRestart(prev: Config, cfg: Config): boolean {
  return changed(prev.frps, cfg.frps) || frpcClientToml(prev) !== frpcClientToml(cfg);
}

export function frpcEnv(cfg: Config, secrets: Secrets): Record<string, string> | { missing: string[] } {
  const missing: string[] = [];
  if (!cfg.frps.addr) missing.push("адрес сервера");
  const token = secrets.get("frpsToken");
  if (!token) missing.push("токен сервера");
  const sk = secrets.get("sk");
  if (!sk) missing.push("ключ туннеля");
  if (missing.length) return { missing };
  return {
    SB_FRPS_ADDR: cfg.frps.addr,
    SB_FRPS_PORT: String(cfg.frps.port),
    SB_FRPS_TOKEN: token!,
    SB_SK: sk!,
  };
}

// Place side (VPS): stcp visitors bound to loopback ports there + the matching .mcp.json.
// This is what the user copies to the place once; it contains secrets, so it is shown on demand only.
export function placeBundle(cfg: Config, secrets: Secrets, basePort = 47911) {
  const user = cfg.frps.user || cfg.clientId;
  const visitors = exposedServices(cfg).map((s) => ({ ...s, bindPort: basePort + SERVICE_SLOTS[s.name] }));
  const toml = [
    `# Agent Bridge visitor for ${cfg.clientId} — keep this file 0600`,
    `serverAddr = "${cfg.frps.addr}"`,
    `serverPort = ${cfg.frps.port}`,
    `user = "${user}"`,
    'auth.method = "token"',
    `auth.token = "${secrets.get("frpsToken") ?? ""}"`,
    "loginFailExit = false",
    "",
    ...visitors.flatMap((v) => [
      "[[visitors]]",
      `name = "${v.name}-visitor"`,
      'type = "stcp"',
      `serverName = "${v.name}"`,
      `secretKey = "${secrets.get("sk") ?? ""}"`,
      'bindAddr = "127.0.0.1"',
      `bindPort = ${v.bindPort}`,
      "",
    ]),
  ].join("\n");
  const mcp = {
    mcpServers: Object.fromEntries(
      visitors.map((v) => [
        `bridge-${v.name}`,
        {
          type: "http",
          url: `http://127.0.0.1:${v.bindPort}/mcp`,
          headers: { Authorization: `Bearer ${secrets.get("gateToken") ?? ""}` },
        },
      ]),
    ),
  };
  return { visitorToml: toml, mcpJson: JSON.stringify(mcp, null, 2) };
}
